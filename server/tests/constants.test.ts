import { ROLES, STATUS, PROJECT_STATUS, LIMITS, PHONE_PATTERN } from "../utils/constants";
import { ERROR_CODES, SUCCESS_CODES } from "../utils/errorCodes";

// These values are shared with the client (client/src/constants/index.js); change both together.
describe("constants", () => {
  it("roles", () => {
    expect(ROLES).toEqual({ ADMIN: "ADMIN", OWNER: "OWNER", FREELANCER: "FREELANCER" });
  });

  it("status codes", () => {
    expect(STATUS).toEqual({ REJECTED: 0, PENDING: 1, ACCEPTED: 2 });
    expect(PROJECT_STATUS).toEqual({ OPEN: "OPEN", CLOSED: "CLOSED" });
  });

  it("error and success codes are their own names and never overlap", () => {
    for (const codes of [ERROR_CODES, SUCCESS_CODES])
      for (const [key, value] of Object.entries(codes)) expect(value).toBe(key);
    expect(Object.keys(ERROR_CODES).filter((k) => Object.hasOwn(SUCCESS_CODES, k))).toEqual([]);
  });

  // The client copies this list (client/src/i18n/serverCodes.test.ts) and needs a translation per code; change both together.
  it("code lists", () => {
    expect(Object.keys(ERROR_CODES)).toEqual([
      "BAD_REQUEST", "INTERNAL_ERROR", "ROUTE_NOT_FOUND", "TOKEN_NOT_CREATED", "RATE_LIMITED", "INVALID_ID",
      "INVALID_SEARCH", "INVALID_SORT", "INVALID_PAGINATION", "PHONE_REQUIRED", "INVALID_PHONE", "LOGIN_FAILED",
      "USER_NOT_FOUND", "INVALID_OTP", "OTP_EXPIRED", "PHONE_NOT_VERIFIED", "DUPLICATE_EMAIL", "INVALID_NAME",
      "INVALID_EMAIL", "INVALID_ROLE", "INVALID_BIOGRAPHY", "INVALID_USERNAME", "PASSWORD_REQUIRED",
      "INVALID_CREDENTIALS", "LOGIN_REQUIRED", "INVALID_TOKEN", "ACCOUNT_NOT_FOUND", "PROFILE_PENDING",
      "PROFILE_REJECTED", "ACCESS_DENIED", "DEMO_ACCOUNT_LOCKED", "INVALID_USER_STATUS", "USER_STATUS_NOT_UPDATED", "PROJECT_NOT_FOUND", "PROJECT_NOT_CREATED",
      "PROJECT_NOT_UPDATED", "PROJECT_STATUS_NOT_UPDATED", "PROJECT_NOT_DELETABLE", "INVALID_PROJECT_TITLE",
      "INVALID_DESCRIPTION", "INVALID_TAGS", "INVALID_CATEGORY", "INVALID_PRICE", "INVALID_DEADLINE",
      "INVALID_PROJECT_STATUS", "PROPOSAL_NOT_FOUND", "PROPOSAL_NOT_CREATED", "PROJECT_NOT_OPEN", "DUPLICATE_PROPOSAL",
      "PROPOSAL_ALREADY_ACCEPTED", "INVALID_DURATION", "INVALID_PROJECT_ID", "INVALID_PROPOSAL_STATUS", "CATEGORY_NOT_FOUND", "CATEGORY_NOT_CREATED",
      "CATEGORY_NOT_UPDATED", "CATEGORY_NOT_DELETED", "DUPLICATE_CATEGORY", "INVALID_CATEGORY_TITLE",
      "INVALID_CATEGORY_ENGLISH_TITLE", "INVALID_CATEGORY_DESCRIPTION", "INVALID_CATEGORY_TYPE",
      "INVALID_AVATAR_TYPE", "AVATAR_TOO_LARGE",
    ]);
    expect(Object.keys(SUCCESS_CODES)).toEqual([
      "OTP_SENT", "OTP_VERIFIED", "OTP_VERIFIED_COMPLETE_PROFILE", "LOGGED_IN", "PROFILE_COMPLETED", "PROFILE_UPDATED",
      "LOGGED_OUT", "USER_ACCEPTED", "USER_REJECTED", "USER_PENDING", "PROJECT_CREATED", "PROJECT_UPDATED",
      "PROJECT_DELETED", "PROJECT_OPENED", "PROJECT_CLOSED", "PROPOSAL_CREATED", "PROPOSAL_ACCEPTED",
      "PROPOSAL_REJECTED", "PROPOSAL_PENDING", "CATEGORY_CREATED", "CATEGORY_UPDATED", "CATEGORY_DELETED",
      "AVATAR_UPDATED",
    ]);
  });

  it("validation limits", () => {
    expect(LIMITS).toEqual({
      PROJECT_TITLE_MIN: 10,
      PROJECT_TITLE_MAX: 30,
      PROJECT_BUDGET_MIN: 100000,
      PROJECT_BUDGET_MAX: 1000000000,
      PROJECT_DESCRIPTION_MIN: 15,
      PROJECT_TAGS_MAX: 20,
      PROPOSAL_DESCRIPTION_MIN: 10,
      PROPOSAL_PRICE_MIN: 10000,
      PROPOSAL_PRICE_MAX: 1000000000,
      PROPOSAL_DURATION_MIN: 1,
      PROPOSAL_DURATION_MAX: 365,
      OTP_MIN: 5,
      OTP_MAX: 6,
      NAME_MIN: 5,
      NAME_MAX: 100,
      PROFILE_NAME_MAX: 50,
      BIOGRAPHY_MAX: 30,
    });
    expect(PHONE_PATTERN.source).toBe("^09[0-9]{9}$");
  });
});
